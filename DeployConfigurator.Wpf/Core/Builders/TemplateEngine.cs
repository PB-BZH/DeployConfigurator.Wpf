namespace DeployConfigurator.Wpf.Core.Builders;

public static class TemplateEngine {
  public static string ReplaceTokens(
      string template,
      Dictionary<string,string> values) {
    foreach (var item in values) {
      template = template.Replace(
          $"__{item.Key}__",
          item.Value
      );
    }

    return template;
  }
}